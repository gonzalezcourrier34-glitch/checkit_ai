"""Normalisation centralisée des verdicts de fact-checking.

Ce module transforme les verdicts hétérogènes produits par les organismes
de fact-checking vers les trois labels standards utilisés par CheckIt.AI :

- true : l'affirmation est considérée comme vraie ;
- false : l'affirmation est considérée comme fausse ou trompeuse ;
- not_classified : le verdict est absent, ambigu ou non convertible
  de manière fiable vers une classification binaire.

Le verdict brut et sa version normalisée sont conservés afin de garantir
la traçabilité des transformations.
"""

