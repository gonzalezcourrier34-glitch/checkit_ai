# Labels standards CheckIt.AI

FACT_CHECK_LABEL_TRUE = "true"
FACT_CHECK_LABEL_FALSE = "false"
FACT_CHECK_LABEL_NOT_CLASSIFIED = "not_classified"

FACT_CHECK_LABELS = {
    FACT_CHECK_LABEL_TRUE,
    FACT_CHECK_LABEL_FALSE,
    FACT_CHECK_LABEL_NOT_CLASSIFIED
}


# Motifs expliquant le résultat de la conversion

REASON_EXACT_MATCH = "exact_match"
REASON_TRUE_MARKER = "true_marker"
REASON_FALSE_MARKER = "false_marker"
REASON_AMBIGUOUS = "ambiguous"
REASON_EMPTY = "empty"
REASON_UNKNOWN = "unknown"


@dataclass(frozen=True, slots=True)
class FactCheckLabelResult:
    """Résultat détaillé de la conversion d'un verdict."""

    raw_value: str
    normalized_value: str
    label: str
    reason: str
    matched_value: str = ""

    @property
    def is_classified(self) -> bool:
        """Indique si le verdict a été converti en true ou false."""

        return self.label in {
            FACT_CHECK_LABEL_TRUE,
            FACT_CHECK_LABEL_FALSE
        }

    @property
    def is_true(self) -> bool:
        """Indique si le verdict est considéré comme vrai."""

        return self.label == FACT_CHECK_LABEL_TRUE

    @property
    def is_false(self) -> bool:
        """Indique si le verdict est considéré comme faux."""

        return self.label == FACT_CHECK_LABEL_FALSE

    def to_dict(self) -> dict[str, str | bool]:
        """Retourne le résultat sous une forme sérialisable."""

        return {
            "raw_value": self.raw_value,
            "normalized_value": self.normalized_value,
            "label": self.label,
            "reason": self.reason,
            "matched_value": self.matched_value,
            "is_classified": self.is_classified
        }


