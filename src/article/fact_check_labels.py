# Expressions permettant de supprimer certains préfixes sans valeur sémantique

RATING_PREFIXES = (
    "rating",
    "verdict",
    "evaluation",
    "fact check",
    "fact-check",
    "factcheck",
    "conclusion",
    "result",
    "resultat",
    "classification",
    "assessment",
    "our rating",
    "notre verdict",
    "notre evaluation"
)


def normalize_fact_check_text(value: Any) -> str:
    """Normalise un verdict avant sa comparaison.

    La fonction retire notamment :

    - les accents ;
    - les différences de casse ;
    - les apostrophes typographiques ;
    - la ponctuation ;
    - les balises ou caractères décoratifs ;
    - les espaces multiples.
    """

    text = clean_text(value).lower()

    if not text:
        return ""

    text = (
        text.replace("’", "'")
        .replace("`", "'")
        .replace("“", '"')
        .replace("”", '"')
        .replace("–", "-")
        .replace("—", "-")
        .replace("−", "-")
        .replace("&", " and ")
    )

    # Retire les accents sans ajouter de dépendance externe.
    decomposed = normalize("NFKD", text)
    text = "".join(
        character
        for character in decomposed
        if not combining(character)
    )

    # Remplace la ponctuation par des espaces sans supprimer
    # les apostrophes utiles aux marqueurs comme "n'a jamais dit".
    text = re.sub(
        r"[\[\]{}()<>|/\\:;,.!?\"*_+=~#@-]",
        " ",
        text
    )

    text = re.sub(r"\s+", " ", text).strip(" -_'")

    return remove_rating_prefix(text)

def remove_rating_prefix(value: str) -> str:
    """Retire un éventuel préfixe comme 'Verdict :' ou 'Rating :'."""

    normalized_value = value.strip()

    for prefix in sorted(RATING_PREFIXES, key=len, reverse=True):
        normalized_prefix = normalize_prefix(prefix)

        if normalized_value == normalized_prefix:
            return ""

        if normalized_value.startswith(f"{normalized_prefix} "):
            return normalized_value[len(normalized_prefix):].strip(" -_")

    return normalized_value


def normalize_prefix(value: str) -> str:
    """Normalise simplement un préfixe déjà connu."""

    decomposed = normalize("NFKD", value.lower())

    return " ".join(
        "".join(
            character
            for character in decomposed
            if not combining(character)
        ).replace("-", " ").split()
    )


def contains_marker(value: str, marker: str) -> bool:
    """Recherche un marqueur en respectant les limites des mots.

    Cela évite par exemple de détecter `true` dans un mot plus long.
    """

    if not value or not marker:
        return False

    pattern = rf"(?<![\w]){re.escape(marker)}(?![\w])"
    return re.search(pattern, value) is not None


def find_first_marker(
    value: str,
    markers: Sequence[str]
) -> str:
    """Retourne le premier marqueur trouvé dans un verdict."""

    # Les marqueurs les plus longs sont contrôlés en premier pour éviter
    # qu'un terme général masque une formulation plus précise.
    for marker in sorted(markers, key=len, reverse=True):
        if contains_marker(value, marker):
            return marker

    return ""


def build_not_classified_result(
    raw_value: str,
    normalized_value: str,
    reason: str,
    matched_value: str = ""
) -> FactCheckLabelResult:
    """Construit un résultat non classifié."""

    return FactCheckLabelResult(
        raw_value=raw_value,
        normalized_value=normalized_value,
        label=FACT_CHECK_LABEL_NOT_CLASSIFIED,
        reason=reason,
        matched_value=matched_value
    )


def classify_fact_check_label(value: Any) -> FactCheckLabelResult:
    """Convertit un verdict de fact-checking vers un label CheckIt.AI.

    L'ordre des vérifications est volontairement strict :

    1. verdict vide ;
    2. correspondance exacte ambiguë ;
    3. correspondance exacte fausse ;
    4. correspondance exacte vraie ;
    5. détection d'une formulation ambiguë ;
    6. détection d'une formulation fausse ;
    7. détection d'une formulation vraie ;
    8. verdict inconnu.

    Les formulations négatives sont contrôlées avant les formulations
    positives afin que `not true` ne soit jamais classé comme `true`.
    """

    raw_value = clean_text(value)
    normalized_value = normalize_fact_check_text(raw_value)

    if not normalized_value:
        return build_not_classified_result(
            raw_value=raw_value,
            normalized_value="",
            reason=REASON_EMPTY
        )

    # Les verdicts ambigus ne doivent jamais être forcés vers true ou false.
    if normalized_value in AMBIGUOUS_EXACT_LABELS:
        
        logger.debug("Verdict AMBIGUOUS : %r", raw_value)
        
        return build_not_classified_result(
            raw_value=raw_value,
            normalized_value=normalized_value,
            reason=REASON_AMBIGUOUS,
            matched_value=normalized_value
        )

    if normalized_value in FALSE_EXACT_LABELS:
        
        logger.debug("Verdict EXACT FALSE : %r", raw_value)
         
        return FactCheckLabelResult(
            raw_value=raw_value,
            normalized_value=normalized_value,
            label=FACT_CHECK_LABEL_FALSE,
            reason=REASON_EXACT_MATCH,
            matched_value=normalized_value
        )

    if normalized_value in TRUE_EXACT_LABELS:
        
        logger.debug("Verdict EXACT TRUE : %r", raw_value)
        
        return FactCheckLabelResult(
            raw_value=raw_value,
            normalized_value=normalized_value,
            label=FACT_CHECK_LABEL_TRUE,
            reason=REASON_EXACT_MATCH,
            matched_value=normalized_value
        )

    ambiguous_marker = find_first_marker(
        normalized_value,
        AMBIGUOUS_MARKERS
    )

    if ambiguous_marker:
        return build_not_classified_result(
            raw_value=raw_value,
            normalized_value=normalized_value,
            reason=REASON_AMBIGUOUS,
            matched_value=ambiguous_marker
        )

    false_marker = find_first_marker(
        normalized_value,
        FALSE_MARKERS
    )
    
    if false_marker:
        return FactCheckLabelResult(
            raw_value=raw_value,
            normalized_value=normalized_value,
            label=FACT_CHECK_LABEL_FALSE,
            reason=REASON_FALSE_MARKER,
            matched_value=false_marker
        )

    true_marker = find_first_marker(
        normalized_value,
        TRUE_MARKERS
    )

    if true_marker:
        return FactCheckLabelResult(
            raw_value=raw_value,
            normalized_value=normalized_value,
            label=FACT_CHECK_LABEL_TRUE,
            reason=REASON_TRUE_MARKER,
            matched_value=true_marker
        )

    logger.debug(
        "Verdict inconnu | brut=%r | normalisé=%r",
        raw_value,
        normalized_value
    )

    return build_not_classified_result(
        raw_value=raw_value,
        normalized_value=normalized_value,
        reason=REASON_UNKNOWN
    )


def get_fact_check_label(value: Any) -> str:
    """Retourne uniquement le label true, false ou not_classified."""

    return classify_fact_check_label(value).label


def is_valid_fact_check_label(value: Any) -> bool:
    """Vérifie qu'une valeur est un label fact-checking standard."""

    normalized_value = normalize_fact_check_text(value).replace(
        " ",
        "_"
    )

    return normalized_value in FACT_CHECK_LABELS


def normalize_existing_fact_check_label(value: Any) -> str:
    """Normalise un label déjà présent dans un article.

    Cette fonction accepte notamment les anciennes valeurs `real` et `fake`
    afin de faciliter la transition vers les nouveaux labels.
    """

    normalized_value = normalize_fact_check_text(value)

    legacy_mapping = {
        "true": FACT_CHECK_LABEL_TRUE,
        "real": FACT_CHECK_LABEL_TRUE,
        "reel": FACT_CHECK_LABEL_TRUE,
        "vrai": FACT_CHECK_LABEL_TRUE,
        "1": FACT_CHECK_LABEL_TRUE,
        "false": FACT_CHECK_LABEL_FALSE,
        "fake": FACT_CHECK_LABEL_FALSE,
        "faux": FACT_CHECK_LABEL_FALSE,
        "0": FACT_CHECK_LABEL_FALSE,
        "not classified": FACT_CHECK_LABEL_NOT_CLASSIFIED,
        "not_classified": FACT_CHECK_LABEL_NOT_CLASSIFIED,
        "unknown": FACT_CHECK_LABEL_NOT_CLASSIFIED,
        "unclassified": FACT_CHECK_LABEL_NOT_CLASSIFIED,
        "non classe": FACT_CHECK_LABEL_NOT_CLASSIFIED,
        "non classee": FACT_CHECK_LABEL_NOT_CLASSIFIED,
        "": FACT_CHECK_LABEL_NOT_CLASSIFIED
    }

    return legacy_mapping.get(
        normalized_value,
        get_fact_check_label(value)
    )


def enrich_article_with_fact_check_label(
    article: Mapping[str, Any],
    raw_rating: Any,
    overwrite_label: bool = True
) -> dict[str, Any]:
    """Ajoute les informations de classification à un article.

    La fonction retourne une copie afin de ne pas modifier silencieusement
    l'objet reçu par l'appelant.
    """

    enriched_article = dict(article)
    result = classify_fact_check_label(raw_rating)

    if overwrite_label or not enriched_article.get("label"):
        enriched_article["label"] = result.label

    enriched_article["fact_check_rating"] = result.raw_value
    enriched_article["fact_check_rating_normalized"] = (
        result.normalized_value
    )
    enriched_article["fact_check_label_reason"] = result.reason
    enriched_article["fact_check_label_match"] = result.matched_value

    return enriched_article